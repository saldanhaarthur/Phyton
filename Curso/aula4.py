# Tipos int e float
# int -> Número inteiro
# O tipo int representa qualquer número positivo ou negativo.
# int sem sinal e considerado número positivo 
print(11)# int 
print(-11)# int
print(0)# int

# float -> número com ponto flutuante 
# O tipo float representa qualquer numero positivo ou negativo com ponto flutuante 
# Sem sinal e considerado positivo 
print(1.1, 10.11)# float
print(0.0)# float
print(-5.5)# float

# A função type mostra o tipo que o python inferiu ao valor.
print( type("Arthur") )
print( type(1) )
print( type(5.5))