#Tipo de dado bool (boolean)
# Ao questionar algo em um programa so existem duas respostas possíveis:
# sim(true) ou não(false)
# Existem vários operadores para 'quastionar'
# Dentre eles o == , que é um operador lógico que questiona se um valor e igual ao outro 

print(10 == 10) # Sim => True (Verdadeiro)
print(10 == 11) # Não => False (Falso)
print( type(10 == 10))# Dessa forma ele vai me dar o tipo do dado e não o valor 
